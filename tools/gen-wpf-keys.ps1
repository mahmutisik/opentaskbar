# Regenerates crates/ot-core/src/hotkey_keys.rs from WPF's Key enum (Windows PowerShell 5.1, PresentationCore).
# Lists only the names OpenTaskbar's C# HotkeyBinding.TryParse accepts, so Rust validation matches it exactly.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName PresentationCore, WindowsBase
$disallowed = 'None','DeadCharProcessed','ImeProcessed','System','LeftCtrl','RightCtrl','LeftAlt','RightAlt',
    'LeftShift','RightShift','LWin','RWin','Escape','Snapshot'
function Test-Vk([int]$vk) {
    $vk -gt 0 -and $vk -le 0xFE -and $vk -notin 0x1B, 0x2C, 0x10, 0x11, 0x12, 0x5B, 0x5C -and -not ($vk -ge 0xA0 -and $vk -le 0xA5)
}
$accepted = foreach ($name in [Enum]::GetNames([System.Windows.Input.Key])) {
    $vk = [System.Windows.Input.KeyInterop]::VirtualKeyFromKey([System.Windows.Input.Key]$name)
    $canonical = [string][System.Windows.Input.KeyInterop]::KeyFromVirtualKey($vk)
    if ($name -notin $disallowed -and (Test-Vk $vk) -and $canonical -notin $disallowed) {
        [pscustomobject]@{ Name = $name.ToLowerInvariant(); Vk = $vk }
    }
}
$lines = $accepted | Sort-Object Name -Unique | ForEach-Object { '    ("{0}", 0x{1:X2}),' -f $_.Name, $_.Vk }
$body = @"
//! WPF ``Key`` enum names accepted by OpenTaskbar's custom hotkey parser, mapped to Win32 virtual-key codes.
//! Generated from PresentationCore (``KeyInterop.VirtualKeyFromKey``) with the C# rejection rules already
//! applied, so a name is listed only when the C# parser would accept it. Lowercase; looked up case-insensitively.
// @generated by tools/gen-wpf-keys.ps1. Do not edit by hand.

pub(crate) static WPF_KEY_VK: &[(&str, u8)] = &[
$($lines -join "`n")
];
"@
$dst = Join-Path $PSScriptRoot '..\crates\ot-core\src\hotkey_keys.rs'
[IO.File]::WriteAllText($dst, $body.Replace("`r`n", "`n"), (New-Object Text.UTF8Encoding $false))
"wrote $($accepted.Count) keys to $dst"
